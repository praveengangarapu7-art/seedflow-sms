import type { Permission } from '@/utils/permissions';

/**
 * Product-wide search catalogue for SeedSphere.
 *
 * Every destination a user can reach lives here once. The same index powers the
 * search bar in the marketing site (outside login) and inside the app shell, so
 * a query returns the same answers in both places — the only difference is that
 * results needing an account are marked with a lock and routed through login.
 *
 * Adding a new page? Add one entry here and it becomes searchable everywhere.
 */

export type SearchModule =
  | 'Platform'
  | 'Procurement'
  | 'Warehouse'
  | 'R&D'
  | 'Processing'
  | 'Production'
  | 'Laboratory'
  | 'Master Data'
  | 'Portals';

export type SearchKind = 'page' | 'action' | 'section';

export interface SearchEntry {
  /** Stable id, used as a React key and for recent-search storage. */
  id: string;
  title: string;
  description: string;
  /** Route to navigate to. A leading `/#` means "landing page, scroll to anchor". */
  path: string;
  module: SearchModule;
  kind: SearchKind;
  /** Extra terms people might type that aren't in the title. */
  keywords: string[];
  /** False for marketing pages and auth screens; true for everything behind login. */
  requiresAuth: boolean;
  /** Role permission gate, when the route has one in AppRoutes. */
  permission?: Permission;
  /** Nudges obvious landmarks (dashboards, main registers) up the list. 0 by default. */
  boost?: number;
}

