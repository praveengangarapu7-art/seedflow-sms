// Helper to generate environmental data
export const generateEnvData = (startDate: string, days: number): EnvironmentalReading[] => {
  const data: EnvironmentalReading[] = [];
  const start = new Date(startDate);
  for (let i = 0; i < days; i++) {
    const current = new Date(start);
    current.setDate(start.getDate() + i);
    data.push({
      date: current.toISOString().split('T')[0],
      temperatureMin: 20 + Math.random() * 5,
      temperatureMax: 29 + Math.random() * 7,
      rainfall: Math.random() > 0.85 ? Math.random() * 25 : 0,
      humidity: 55 + Math.random() * 35,
      soilMoisture: 25 + Math.random() * 45,
      source: 'IoT sensor',
    });
  }
  return data;
};

// Helper to generate plot map layout programmatically
export const generatePlotMap = (entries: TrialEntry[], replications: number = 3, status: PlotCell['status'] = 'Growing'): PlotCell[] => {
  const plots: PlotCell[] = [];
  let plotNum = 1;
  for (let r = 1; r <= replications; r++) {
    entries.forEach((entry) => {
      plots.push({
        plotNumber: `P-${String(plotNum).padStart(3, '0')}`,
        row: Math.floor((plotNum - 1) / 6) + 1,
        col: ((plotNum - 1) % 6) + 1,
        entryCode: entry.code,
        replication: r,
        area: 12,
        status: status,
      });
      plotNum++;
    });
  }
  return plots;
};

