import { useCallback, useEffect, useState } from 'react';
import { jsPDF } from 'jspdf';
import { Download, FileSignature, PlusCircle } from 'lucide-react';
import { Button } from '@/components/common/Button/Button';
import { Input } from '@/components/common/Input/Input';
import { KpiCard } from '@/components/common/KpiCard/KpiCard';
import { useToast } from '@/components/common/Toast/ToastContext';
import {
  DEMO_ACCOUNTS,
  fetchCertificates,
  fetchComplianceChain,
  fetchQualityMetrics,
  fetchSeedLots,
  generateQualityCertificate,
  login,
  recordPhytosanitaryCertificate,
  recordPurityTest,
  recordViabilityTest,
  signQualityCertificate,
  type ComplianceChainResult,
  type QualityCertificateRow,
  type QualityMetricsSummary,
  type RealtimeSeedLot,
} from '@/services/seedLotRealtimeClient';
import styles from './SeedComplianceReport.module.css';

function statusClass(status: string): string {
  return (
    {
      draft: styles.statusDraft,
      issued: styles.statusIssued,
      superseded: styles.statusSuperseded,
      revoked: styles.statusRevoked,
      valid: styles.statusValid,
      expired: styles.statusExpired,
    }[status] ?? styles.statusDraft
  );
}

function formatRate(rate: { averagePercent: number | null; testCount: number }): string {
  if (rate.averagePercent == null) return 'Not tested';
  return `${rate.averagePercent}% (${rate.testCount} test${rate.testCount === 1 ? '' : 's'})`;
}

function exportCertificatePdf(cert: QualityCertificateRow) {
  const snapshot = cert.snapshot;
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  let y = 56;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(17);
  doc.text('SeedSphere Seed Quality Compliance Certificate', 40, y);
  y += 20;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(90);
  doc.text(`Certificate Version v${cert.version}  •  Status: ${cert.status.toUpperCase()}`, 40, y);
  doc.setTextColor(0);
  y += 34;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Seed Lot Information', 40, y);
  y += 18;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  [
    `Lot Code: ${snapshot.lotCode}`,
    `Crop / Variety: ${snapshot.crop} — ${snapshot.variety}`,
    `Certification Stage: ${snapshot.stage}`,
  ].forEach((line) => {
    doc.text(line, 40, y);
    y += 15;
  });
  y += 12;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Quality Metrics', 40, y);
  y += 18;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  [
    `Purity Rate: ${formatRate(snapshot.purity)}`,
    `Viability: ${formatRate(snapshot.viability)}`,
    `Germination: ${formatRate(snapshot.germination)}`,
  ].forEach((line) => {
    doc.text(line, 40, y);
    y += 15;
  });
  y += 12;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Phytosanitary Certificates', 40, y);
  y += 18;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  if (snapshot.phytosanitary.length === 0) {
    doc.text('None on record.', 40, y);
    y += 15;
  } else {
    snapshot.phytosanitary.forEach((cert2) => {
      const expiry = cert2.expiry_date ? `, expires ${cert2.expiry_date.slice(0, 10)}` : '';
      doc.text(
        `${cert2.certificate_number} — ${cert2.issuing_authority} (${cert2.status}), issued ${cert2.issue_date.slice(0, 10)}${expiry}`,
        40,
        y,
      );
      y += 15;
    });
  }
  y += 20;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('Regulatory Sign-off', 40, y);
  y += 24;
  doc.setDrawColor(150);
  doc.line(40, y, 260, y);
  y += 14;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  if (cert.signed_by) {
    doc.text(`${cert.signed_by} (${cert.signature_role})`, 40, y);
    y += 15;
    doc.text(`Signed: ${new Date(cert.signed_at!).toLocaleString()}`, 40, y);
  } else {
    doc.text('Awaiting signature', 40, y);
  }

  doc.setFontSize(8);
  doc.setTextColor(140);
  doc.text(
    `Generated by ${cert.generated_by} on ${new Date(cert.created_at).toLocaleString()} — SeedSphere Compliance Module`,
    40,
    800,
  );

  doc.save(`${snapshot.lotCode}-quality-certificate-v${cert.version}.pdf`);
}

export default function SeedComplianceReport() {
  const { addToast } = useToast();

  const [accountIndex, setAccountIndex] = useState(3); // Inspector by default
  const [token, setToken] = useState<string | null>(null);
  const [lots, setLots] = useState<RealtimeSeedLot[]>([]);
  const [selectedLotId, setSelectedLotId] = useState('');

  const [metrics, setMetrics] = useState<QualityMetricsSummary | null>(null);
  const [chain, setChain] = useState<ComplianceChainResult | null>(null);
  const [certificates, setCertificates] = useState<QualityCertificateRow[]>([]);

  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [generating, setGenerating] = useState(false);
  const [signingId, setSigningId] = useState<string | null>(null);

  const [purityLotId, setPurityLotId] = useState('');
  const [purityWeight, setPurityWeight] = useState('500');
  const [purityPure, setPurityPure] = useState('');
  const [purityError, setPurityError] = useState<string | null>(null);
  const [puritySubmitting, setPuritySubmitting] = useState(false);

  const [viabilityLotId, setViabilityLotId] = useState('');
  const [viabilitySample, setViabilitySample] = useState('400');
  const [viabilityCount, setViabilityCount] = useState('');
  const [viabilityError, setViabilityError] = useState<string | null>(null);
  const [viabilitySubmitting, setViabilitySubmitting] = useState(false);

  const [phytoLotId, setPhytoLotId] = useState('');
  const [phytoNumber, setPhytoNumber] = useState('');
  const [phytoAuthority, setPhytoAuthority] = useState('State Plant Quarantine Authority');
  const [phytoIssueDate, setPhytoIssueDate] = useState('');
  const [phytoError, setPhytoError] = useState<string | null>(null);
  const [phytoSubmitting, setPhytoSubmitting] = useState(false);

  const loadLotData = useCallback(async (accessToken: string, lotId: string) => {
    if (!lotId) return;
    setLoading(true);
    setError(null);
    try {
      const [metricsResult, chainResult, certificatesResult] = await Promise.all([
        fetchQualityMetrics(accessToken, lotId),
        fetchComplianceChain(accessToken, lotId),
        fetchCertificates(accessToken, lotId),
      ]);
      setMetrics(metricsResult);
      setChain(chainResult);
      setCertificates(certificatesResult);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unable to load compliance data');
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    let cancelled = false;
    const account = DEMO_ACCOUNTS[accountIndex];

    async function bootstrap() {
      setLoading(true);
      setError(null);
      try {
        const { accessToken } = await login(account.email, account.password);
        if (cancelled) return;
        setToken(accessToken);

        const lotsResult = await fetchSeedLots(accessToken);
        if (cancelled) return;
        setLots(lotsResult);

        setSelectedLotId((current) => {
          if (current) return current;
          const preferred = lotsResult.find((lot) => lot.stage === 'Certified') ?? lotsResult[0];
          return preferred?.id ?? '';
        });
      } catch (err) {
        if (!cancelled) {
          setError(err instanceof Error ? err.message : 'Unable to connect to the compliance service');
          setLoading(false);
        }
      }
    }

    void bootstrap();
    return () => {
      cancelled = true;
    };
  }, [accountIndex]);

  useEffect(() => {
    if (token && selectedLotId) {
      void loadLotData(token, selectedLotId);
    }
  }, [token, selectedLotId, loadLotData]);

  const handleGenerate = async () => {
    if (!token || !selectedLotId) return;
    setGenerating(true);
    try {
      await generateQualityCertificate(token, selectedLotId);
      addToast('New certificate version generated as a draft', 'success');
      await loadLotData(token, selectedLotId);
    } catch (err) {
      addToast(err instanceof Error ? err.message : 'Unable to generate certificate', 'error');
    } finally {
      setGenerating(false);
    }
  };

  const handleSign = async (certificateId: string) => {
    if (!token) return;
    setSigningId(certificateId);
    try {
      await signQualityCertificate(token, certificateId);
      addToast('Certificate signed and issued', 'success');
      await loadLotData(token, selectedLotId);
    } catch (err) {
      addToast(err instanceof Error ? err.message : 'Unable to sign certificate', 'error');
    } finally {
      setSigningId(null);
    }
  };

  const handleRecordPurity = async (event: React.FormEvent) => {
    event.preventDefault();
    setPurityError(null);
    if (!token) return;
    if (!purityLotId) {
      setPurityError('Select a seed lot.');
      return;
    }
    const weight = Number(purityWeight);
    const pure = Number(purityPure);
    if (!purityWeight || Number.isNaN(weight) || weight <= 0) {
      setPurityError('Sample weight must be a positive number.');
      return;
    }
    if (!purityPure || Number.isNaN(pure) || pure < 0) {
      setPurityError('Pure seed weight must be a non-negative number.');
      return;
    }
    if (pure > weight) {
      setPurityError('Pure seed weight cannot exceed sample weight.');
      return;
    }

    setPuritySubmitting(true);
    try {
      await recordPurityTest(token, { seedLotId: purityLotId, sampleWeight: weight, pureSeedWeight: pure });
      addToast('Purity test recorded', 'success');
      setPurityPure('');
      if (purityLotId === selectedLotId) await loadLotData(token, selectedLotId);
    } catch (err) {
      const message = err instanceof Error ? err.message : 'Unable to record purity test';
      setPurityError(message);
      addToast(message, 'error');
    } finally {
      setPuritySubmitting(false);
    }
  };

  const handleRecordViability = async (event: React.FormEvent) => {
    event.preventDefault();
    setViabilityError(null);
    if (!token) return;
    if (!viabilityLotId) {
      setViabilityError('Select a seed lot.');
      return;
    }
    const sample = Number(viabilitySample);
    const viable = Number(viabilityCount);
    if (!viabilitySample || !Number.isInteger(sample) || sample <= 0) {
      setViabilityError('Sample size must be a positive whole number.');
      return;
    }
    if (!viabilityCount || !Number.isInteger(viable) || viable < 0) {
      setViabilityError('Viable count must be a non-negative whole number.');
      return;
    }
    if (viable > sample) {
      setViabilityError('Viable count cannot exceed the sample size.');
      return;
    }

    setViabilitySubmitting(true);
    try {
      await recordViabilityTest(token, { seedLotId: viabilityLotId, sampleSize: sample, viableCount: viable });
      addToast('Viability test recorded', 'success');
      setViabilityCount('');
      if (viabilityLotId === selectedLotId) await loadLotData(token, selectedLotId);
    } catch (err) {
      const message = err instanceof Error ? err.message : 'Unable to record viability test';
      setViabilityError(message);
      addToast(message, 'error');
    } finally {
      setViabilitySubmitting(false);
    }
  };

  const handleRecordPhyto = async (event: React.FormEvent) => {
    event.preventDefault();
    setPhytoError(null);
    if (!token) return;
    if (!phytoLotId) {
      setPhytoError('Select a seed lot.');
      return;
    }
    if (!phytoNumber.trim()) {
      setPhytoError('Certificate number is required.');
      return;
    }
    if (!phytoAuthority.trim()) {
      setPhytoError('Issuing authority is required.');
      return;
    }
    if (!phytoIssueDate) {
      setPhytoError('Issue date is required.');
      return;
    }

    setPhytoSubmitting(true);
    try {
      await recordPhytosanitaryCertificate(token, {
        seedLotId: phytoLotId,
        certificateNumber: phytoNumber.trim(),
        issuingAuthority: phytoAuthority.trim(),
        issueDate: phytoIssueDate,
      });
      addToast('Phytosanitary certificate recorded', 'success');
      setPhytoNumber('');
      if (phytoLotId === selectedLotId) await loadLotData(token, selectedLotId);
    } catch (err) {
      const message = err instanceof Error ? err.message : 'Unable to record phytosanitary certificate';
      setPhytoError(message);
      addToast(message, 'error');
    } finally {
      setPhytoSubmitting(false);
    }
  };

  return (
    <div className={styles.page}>
      <div className={styles.header}>
        <div>
          <h1 className={styles.title}>Compliance &amp; Quality Reports</h1>
          <p className={styles.subtitle}>
            Purity, viability, germination, and phytosanitary status per lot — with versioned, signable quality certificates.
          </p>
        </div>
        <div className={styles.controls}>
          <select className={styles.select} value={accountIndex} onChange={(e) => setAccountIndex(Number(e.target.value))}>
            {DEMO_ACCOUNTS.map((account, index) => (
              <option key={account.email} value={index}>
                Viewing as: {account.role}
              </option>
            ))}
          </select>
          <select className={styles.select} value={selectedLotId} onChange={(e) => setSelectedLotId(e.target.value)}>
            <option value="">Select a seed lot</option>
            {lots
              .slice()
              .sort((a, b) => a.lot_code.localeCompare(b.lot_code))
              .map((lot) => (
                <option key={lot.id} value={lot.id}>
                  {lot.lot_code} — {lot.stage}
                </option>
              ))}
          </select>
        </div>
      </div>

      {error ? <div className={styles.card}><span className={styles.errorText}>{error}</span></div> : null}

      {metrics ? (
        <div className={styles.kpiRow}>
          <KpiCard title="Purity Rate" value={metrics.purity.averagePercent != null ? `${metrics.purity.averagePercent}%` : '—'} subValue={`${metrics.purity.testCount} tests`} icon={FileSignature} />
          <KpiCard title="Viability" value={metrics.viability.averagePercent != null ? `${metrics.viability.averagePercent}%` : '—'} subValue={`${metrics.viability.testCount} tests`} icon={FileSignature} />
          <KpiCard title="Germination" value={metrics.germination.averagePercent != null ? `${metrics.germination.averagePercent}%` : '—'} subValue={`${metrics.germination.testCount} tests`} icon={FileSignature} />
        </div>
      ) : null}

      <div className={styles.grid}>
        <div>
          <div className={styles.card}>
            <h2 className={styles.sectionTitle}>Quality Certificates</h2>
            <p className={styles.sectionSubtitle}>Each generation is a new immutable version; signing one supersedes the previously issued version.</p>
            <div className={styles.actionsRow}>
              <Button leftIcon={PlusCircle} onClick={() => void handleGenerate()} isLoading={generating} disabled={!selectedLotId || loading}>
                Generate New Version
              </Button>
            </div>
            {certificates.length === 0 ? (
              <div className={styles.emptyState}>No certificates generated for this lot yet.</div>
            ) : (
              certificates.map((cert) => (
                <div key={cert.id} className={styles.certRow}>
                  <div>
                    <span className={`${styles.statusBadge} ${statusClass(cert.status)}`}>{cert.status}</span>
                    <strong>Version {cert.version}</strong>
                    <div className={styles.certMeta}>
                      Generated by {cert.generated_by} · {new Date(cert.created_at).toLocaleString()}
                      {cert.signed_by ? (
                        <> · Signed by {cert.signed_by} ({cert.signature_role}) on {new Date(cert.signed_at!).toLocaleString()}</>
                      ) : null}
                    </div>
                  </div>
                  <div className={styles.certActions}>
                    {cert.status === 'draft' ? (
                      <Button size="sm" leftIcon={FileSignature} isLoading={signingId === cert.id} onClick={() => void handleSign(cert.id)}>
                        Sign &amp; Issue
                      </Button>
                    ) : null}
                    <Button size="sm" variant="secondary" leftIcon={Download} onClick={() => exportCertificatePdf(cert)}>
                      Export PDF
                    </Button>
                  </div>
                </div>
              ))
            )}
          </div>

          <div className={styles.card}>
            <h2 className={styles.sectionTitle}>Certification Chain by Lifecycle Stage</h2>
            <p className={styles.sectionSubtitle}>Quality metrics for this lot and every ancestor back to its Breeder source.</p>
            {!chain ? (
              <div className={styles.emptyState}>Select a seed lot to see its certification chain.</div>
            ) : (
              <div style={{ overflowX: 'auto' }}>
                <table className={styles.chainTable}>
                  <thead>
                    <tr>
                      <th>Stage</th>
                      <th>Lot Code</th>
                      <th>Purity</th>
                      <th>Viability</th>
                      <th>Germination</th>
                    </tr>
                  </thead>
                  <tbody>
                    {chain.ancestorChain.map((node) => (
                      <tr key={node.seedLotId}>
                        <td>{node.stage}</td>
                        <td>{node.lotCode}</td>
                        <td>{formatRate(node.purity)}</td>
                        <td>{formatRate(node.viability)}</td>
                        <td>{formatRate(node.germination)}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </div>

          <div className={styles.card}>
            <h2 className={styles.sectionTitle}>Phytosanitary Certificates</h2>
            {!metrics || metrics.phytosanitary.length === 0 ? (
              <div className={styles.emptyState}>No phytosanitary certificates on record for this lot.</div>
            ) : (
              metrics.phytosanitary.map((cert) => (
                <div key={cert.id} className={styles.phytoRow}>
                  <span className={`${styles.statusBadge} ${statusClass(cert.status)}`}>{cert.status}</span>
                  <strong>{cert.certificate_number}</strong> — {cert.issuing_authority}
                  <div className={styles.certMeta}>
                    Issued {cert.issue_date.slice(0, 10)}
                    {cert.expiry_date ? <> · Expires {cert.expiry_date.slice(0, 10)}</> : null}
                  </div>
                </div>
              ))
            )}
          </div>
        </div>

        <div>
          <div className={styles.card}>
            <h2 className={styles.sectionTitle}>Record Purity Test</h2>
            <form className={styles.form} onSubmit={handleRecordPurity}>
              {purityError ? <span className={styles.errorText}>{purityError}</span> : null}
              <div className={styles.field}>
                <label className={styles.label} htmlFor="purityLotId">Seed Lot</label>
                <select id="purityLotId" className={styles.select} value={purityLotId} onChange={(e) => setPurityLotId(e.target.value)}>
                  <option value="">Select a seed lot</option>
                  {lots.map((lot) => (
                    <option key={lot.id} value={lot.id}>{lot.lot_code} — {lot.stage}</option>
                  ))}
                </select>
              </div>
              <div className={styles.formRow}>
                <div className={styles.field}>
                  <label className={styles.label} htmlFor="purityWeight">Sample Weight (g)</label>
                  <Input id="purityWeight" type="number" min="0" value={purityWeight} onChange={(e) => setPurityWeight(e.target.value)} />
                </div>
                <div className={styles.field}>
                  <label className={styles.label} htmlFor="purityPure">Pure Seed Weight (g)</label>
                  <Input id="purityPure" type="number" min="0" value={purityPure} onChange={(e) => setPurityPure(e.target.value)} placeholder="e.g. 480" />
                </div>
              </div>
              <Button type="submit" isLoading={puritySubmitting}>Record Purity Test</Button>
            </form>
          </div>

          <div className={styles.card}>
            <h2 className={styles.sectionTitle}>Record Viability Test</h2>
            <form className={styles.form} onSubmit={handleRecordViability}>
              {viabilityError ? <span className={styles.errorText}>{viabilityError}</span> : null}
              <div className={styles.field}>
                <label className={styles.label} htmlFor="viabilityLotId">Seed Lot</label>
                <select id="viabilityLotId" className={styles.select} value={viabilityLotId} onChange={(e) => setViabilityLotId(e.target.value)}>
                  <option value="">Select a seed lot</option>
                  {lots.map((lot) => (
                    <option key={lot.id} value={lot.id}>{lot.lot_code} — {lot.stage}</option>
                  ))}
                </select>
              </div>
              <div className={styles.formRow}>
                <div className={styles.field}>
                  <label className={styles.label} htmlFor="viabilitySample">Sample Size</label>
                  <Input id="viabilitySample" type="number" min="1" value={viabilitySample} onChange={(e) => setViabilitySample(e.target.value)} />
                </div>
                <div className={styles.field}>
                  <label className={styles.label} htmlFor="viabilityCount">Viable Count</label>
                  <Input id="viabilityCount" type="number" min="0" value={viabilityCount} onChange={(e) => setViabilityCount(e.target.value)} placeholder="e.g. 370" />
                </div>
              </div>
              <Button type="submit" isLoading={viabilitySubmitting}>Record Viability Test</Button>
            </form>
          </div>

          <div className={styles.card}>
            <h2 className={styles.sectionTitle}>Record Phytosanitary Certificate</h2>
            <form className={styles.form} onSubmit={handleRecordPhyto}>
              {phytoError ? <span className={styles.errorText}>{phytoError}</span> : null}
              <div className={styles.field}>
                <label className={styles.label} htmlFor="phytoLotId">Seed Lot</label>
                <select id="phytoLotId" className={styles.select} value={phytoLotId} onChange={(e) => setPhytoLotId(e.target.value)}>
                  <option value="">Select a seed lot</option>
                  {lots.map((lot) => (
                    <option key={lot.id} value={lot.id}>{lot.lot_code} — {lot.stage}</option>
                  ))}
                </select>
              </div>
              <div className={styles.field}>
                <label className={styles.label} htmlFor="phytoNumber">Certificate Number</label>
                <Input id="phytoNumber" value={phytoNumber} onChange={(e) => setPhytoNumber(e.target.value)} placeholder="e.g. PSC-2026-0005" />
              </div>
              <div className={styles.field}>
                <label className={styles.label} htmlFor="phytoAuthority">Issuing Authority</label>
                <Input id="phytoAuthority" value={phytoAuthority} onChange={(e) => setPhytoAuthority(e.target.value)} />
              </div>
              <div className={styles.field}>
                <label className={styles.label} htmlFor="phytoIssueDate">Issue Date</label>
                <Input id="phytoIssueDate" type="date" value={phytoIssueDate} onChange={(e) => setPhytoIssueDate(e.target.value)} />
              </div>
              <Button type="submit" isLoading={phytoSubmitting}>Record Certificate</Button>
            </form>
          </div>
        </div>
      </div>
    </div>
  );
}
